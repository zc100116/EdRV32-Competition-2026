// File: tb.sv
// Spec: disp-spec 4-6; SoC 7.1.
// Description: Register reset, alignment, handoff, IRQ priority and deferred local reset.
// Clock domain: test memory clock.
module tb;
    reg clk = 0;
    always #5 clk = ~clk;
    reg rst_n = 0;
    reg [11:0] paddr = 0;
    reg psel = 0;
    reg penable = 0;
    reg pwrite = 0;
    reg [31:0] pwdata = 0;
    reg [3:0] pstrb = 0;
    wire pready;
    wire [31:0] prdata;
    wire pslverr;
    wire enable;
    wire [31:0] next_base;
    wire [31:0] stride;
    wire soft_clear;
    reg busy = 0;
    reg frame_start = 0;
    reg underflow = 0;
    reg dma_err = 0;
    reg underflow1 = 0;
    reg [31:0] perf5 = 0;
    reg [31:0] perf6 = 0;
    reg urgent = 0;
    reg delayed_req = 0;
    reg [31:0] perf0 = 0;
    reg [31:0] perf1 = 0;
    reg [31:0] perf2 = 0;
    wire [31:0] scan_cnt;
    wire irq;
    edrv32_disp_regs dut (
        .clk_i(clk), .rst_n_i({4{rst_n}}), .apb_paddr_i(paddr), .apb_psel_i(psel),
        .apb_penable_i(penable), .apb_pwrite_i(pwrite), .apb_pwdata_i(pwdata),
        .apb_pstrb_i(pstrb), .apb_pready_o(pready), .apb_prdata_o(prdata),
        .apb_pslverr_o(pslverr), .enable_o(enable), .next_base_o(next_base),
        .l0_scroll_o(), .layer_ctrl_o(), .l1_next_base_o(), .l1_stride_o(),
        .l1_pos_o(), .l1_size_o(), .l1_opa_o(), .underflow1_i(underflow1),
        .perf5_i(perf5), .perf6_i(perf6), .stride_o(stride),
        .soft_clear_o(soft_clear), .busy_i(busy),
        .frame_start_i(frame_start), .underflow_i(underflow), .dma_err_i(dma_err),
        .urgent_i(urgent), .delayed_req_i(delayed_req), .perf0_i(perf0),
        .perf1_i(perf1), .perf2_i(perf2), .scan_cnt_o(scan_cnt), .irq_o(irq)
    );
    task automatic tick;
        @(posedge clk);
        #1;
        @(negedge clk);
    endtask
    task automatic write_reg(input [11:0] addr, input [31:0] value);
        paddr = addr;
        pwdata = value;
        pwrite = 1;
        psel = 1;
        penable = 0;
        tick();
        penable = 1;
        tick();
        psel = 0;
        penable = 0;
        pwrite = 0;
    endtask
    task automatic check_reg(input [11:0] addr, input [31:0] expected);
        paddr = addr;
        psel = 1;
        penable = 0;
        pwrite = 0;
        tick();
        penable = 1;
        #1;
        if (!pready || pslverr || prdata !== expected)
            $fatal(1, "FAIL reg %h = %h expected=%h", addr, prdata, expected);
        tick();
        psel = 0;
        penable = 0;
    endtask
    task automatic start_frame;
        frame_start = 1;
        tick();
        frame_start = 0;
    endtask
    initial begin
        repeat (3) @(negedge clk);
        rst_n = 1;
        check_reg('h000, 'h0005_0002);
        check_reg('h004, 0);
        check_reg('h008, 2);
        check_reg('h104, 'ha00);
        for (int offset = 'h40; offset <= 'h7c; offset += 4) check_reg(12'(offset), 0);
        check_reg('h108, 0);
        check_reg('h10c, 0);
        check_reg('h110, 0);
        check_reg('h114, 0);
        check_reg('h118, 1);
        check_reg('h120, 0);
        check_reg('h124, 'h1400);
        check_reg('h128, 0);
        check_reg('h12c, 'h02d00500);
        check_reg('h130, 255);
        check_reg('h134, 0);
        check_reg('h138, 0);
        write_reg('h00c, '1);
        check_reg('h00c, 'h306);
        write_reg('h100, 'h1234_5fff);
        write_reg('h104, 'h9876_123f);
        check_reg('h100, 'h1234_5000);
        check_reg('h104, 'h1220);
        if (next_base != 'h12345000 || stride != 'h1220) $fatal(1, "FAIL cfg outputs");
        write_reg('h004, 3);
        check_reg('h004, 1);
        start_frame();
        check_reg('h108, 'h1234_5000);
        check_reg('h10c, 0);
        check_reg('h110, 1);
        check_reg('h02c, 1);
        check_reg('h010, 4);
        if (!irq) $fatal(1, "FAIL frame IRQ");
        write_reg('h010, '1);
        start_frame();
        check_reg('h010, 4);
        write_reg('h010, '1);
        write_reg('h100, 'h2000_0123);
        check_reg('h108, 'h1234_5000);
        start_frame();
        check_reg('h108, 'h2000_0000);
        check_reg('h10c, 'h1234_5000);
        check_reg('h110, 3);
        underflow = 1;
        tick();
        underflow = 0;
        check_reg('h014, 1);
        check_reg('h008, 6);
        dma_err = 1;
        tick();
        dma_err = 0;
        check_reg('h014, 2);
        write_reg('h010, 2);
        check_reg('h014, 0);
        check_reg('h008, 2);
        // A new error wins over simultaneous RW1C.
        paddr = 'h010;
        psel = 1;
        penable = 0;
        pwrite = 1;
        pwdata = 2;
        tick();
        penable = 1;
        underflow = 1;
        tick();
        psel = 0;
        penable = 0;
        pwrite = 0;
        underflow = 0;
        check_reg('h014, 1);
        check_reg('h010, 'h106);
        perf0 = 7;
        perf1 = 2;
        perf2 = 93;
        urgent = 1;
        delayed_req = 1;
        tick();
        delayed_req = 0;
        repeat (8) tick();
        urgent = 0;
        tick();
        check_reg('h040, 7);
        check_reg('h044, 2);
        check_reg('h048, 93);
        check_reg('h04c, 9);
        check_reg('h050, 1);
        write_reg('h004, 5);
        check_reg('h004, 0);
        write_reg('h020, '1);
        write_reg('h024, '1);
        write_reg('h028, '1);
        write_reg('h180, '1);
        check_reg('h020, 0);
        check_reg('h024, 0);
        check_reg('h028, 0);
        check_reg('h180, 0);
        busy = 1;
        write_reg('h004, 9);
        if (soft_clear || enable) $fatal(1, "FAIL reset did not wait for drain");
        repeat (3) tick();
        check_reg('h110, 3);
        perf0 = 10;
        perf1 = 3;
        perf2 = 99;
        busy = 0;
        // STATUS and the drain decision use the registered BUSY sample.
        repeat (2) tick();
        if (!soft_clear) $fatal(1, "FAIL missing deferred reset completion");
        tick();
        check_reg('h004, 0);
        check_reg('h00c, 0);
        check_reg('h010, 0);
        check_reg('h014, 0);
        check_reg('h100, 0);
        check_reg('h104, 'ha00);
        check_reg('h108, 0);
        check_reg('h10c, 0);
        check_reg('h110, 0);
        for (int offset = 'h40; offset <= 'h7c; offset += 4) check_reg(12'(offset), 0);
        if (scan_cnt != 0 || irq) $fatal(1, "FAIL reset bases/IRQ");
        perf0++;
        perf1++;
        perf2 += 5;
        tick();
        check_reg('h040, 1);
        check_reg('h044, 1);
        check_reg('h048, 5);
        // New shadow registers mask reserved bits, with independent per-layer release.
        write_reg('h114, '1);
        check_reg('h114, 'h0fff7fff);
        write_reg('h120, 'h34567fff);
        write_reg('h124, 'hffff2345);
        write_reg('h128, '1);
        write_reg('h12c, '1);
        write_reg('h130, 'h12345678);
        check_reg('h120, 'h34567000);
        check_reg('h124, 'h2340);
        check_reg('h128, 'h03ff07f8);
        check_reg('h12c, 'h03ff07f8);
        check_reg('h130, 'h78);
        write_reg('h118, 'hfffffffe);
        check_reg('h118, 2);
        start_frame();
        check_reg('h010, 4);
        check_reg('h134, 'h34567000);
        write_reg('h010, '1);
        // Changing position, size, opacity or scroll never releases a Surface.
        write_reg('h128, 8);
        write_reg('h12c, 'h10008);
        write_reg('h130, 255);
        write_reg('h114, 1);
        start_frame();
        check_reg('h010, 4);
        write_reg('h010, '1);
        write_reg('h120, 'h40000000);
        start_frame();
        check_reg('h010, 'h204);
        check_reg('h134, 'h40000000);
        check_reg('h138, 'h34567000);
        write_reg('h010, '1);
        write_reg('h118, 0);
        start_frame();
        check_reg('h010, 'h204);
        check_reg('h138, 'h40000000);
        write_reg('h010, '1);
        start_frame();
        check_reg('h010, 4);
        underflow1 = 1;
        tick();
        underflow1 = 0;
        check_reg('h014, 3);
        write_reg('h010, 2);
        check_reg('h014, 0);
        perf5 = 17;
        perf6 = 987;
        tick();
        check_reg('h054, 17);
        check_reg('h058, 987);
        write_reg('h004, 8);
        repeat (4) tick();
        check_reg('h054, 0);
        check_reg('h058, 0);
        perf5++;
        perf6 += 11;
        tick();
        check_reg('h054, 1);
        check_reg('h058, 11);
        check_reg('h114, 0);
        check_reg('h118, 1);
        check_reg('h124, 'h1400);
        check_reg('h12c, 'h02d00500);
        check_reg('h130, 255);
        write_reg('h100, 'h6000);
        write_reg('h120, 'h7000);
        write_reg('h118, 3);
        start_frame();
        check_reg('h010, 4);
        write_reg('h010, '1);
        write_reg('h118, 0);
        start_frame();
        check_reg('h010, 'h304);
        check_reg('h10c, 'h6000);
        check_reg('h138, 'h7000);
        write_reg('h010, '1);
        start_frame();
        check_reg('h010, 4);
        write_reg('h010, '1);
        write_reg('h100, 'h8000);
        write_reg('h120, 'h9000);
        start_frame();
        check_reg('h108, 'h6000);
        check_reg('h134, 'h7000);
        check_reg('h010, 4);
        write_reg('h010, '1);
        write_reg('h118, 3);
        start_frame();
        check_reg('h010, 4);
        write_reg('h010, '1);
        write_reg('h100, 'ha000);
        write_reg('h120, 'hb000);
        start_frame();
        check_reg('h010, 'h304);
        check_reg('h10c, 'h8000);
        check_reg('h138, 'h9000);
        $display("PASS regs: frame handoff, alignment, IRQ/RW1C, counters, deferred SOFT_RST");
        $finish;
    end
endmodule
