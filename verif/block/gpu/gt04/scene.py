def build(c, rng):
    c.ready()
    c.matrix([.5, 0, 0, 0, 0, .5, 0, 0, 0, 0, .1, 0, 0, 0, .5, 0])
    for points in [[(-1, -1, -1), (1, -1, 2), (0, 1, 2)],
                   [(-1, -1, -1), (1, -1, -1), (0, 1, 2)],
                   [(-1, -1, 2), (1, -1, 2), (0, 1, 2)],
                   [(-1, -1, -1), (1, -1, -1), (0, 1, -1)],
                   [(-12, -1, 2), (1, -1, 2), (0, 1, 2)],
                   [(-1, -1, 2), (12, -1, 2), (0, 1, 2)],
                   [(-1, -12, 2), (1, -1, 2), (0, 1, 2)],
                   [(-1, -1, 2), (1, -1, 2), (0, 12, 2)],
                   [(-12, -12, -1), (12, -1, 2), (0, 12, 2)],
                   [(12, -1, 2), (14, -1, 2), (13, 1, 2)]]:
        c.clear()
        c.triangles(points)
        c.resolve()
