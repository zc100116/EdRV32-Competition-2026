#!/usr/bin/env python3
# File: run.py
# Spec: Task T-BN1; npu-spec 3/4; CLAUDE.md 9.2.
# Description: Generate a minimal CONV/reference, build BIOS/SRAM and run B3N.
# Clock domain: none (host tool).
"""Run the NPU plus ETH board connectivity simulation."""
import argparse
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from tools.fpga.mem_init import pack_image  # noqa: E402
from tools.regress import expand_files  # noqa: E402

HERE = Path(__file__).resolve().parent
OUT = ROOT / 'build/board_npu'
PYTHON = Path.home() / '.local/opt/edrv32-py/bin/python'
PASS = 'PASS board_npu BIOS, NPU ID, removed VIN SLVERR, PLIC13 DONE, output compare'


def command(args, log):
    log.parent.mkdir(parents=True, exist_ok=True)
    with log.open('w') as output:
        subprocess.run(args, cwd=ROOT, stdout=output, stderr=subprocess.STDOUT, check=True)


def read_hex(path):
    """Read the tools/npu 256-bit sparse interchange format into bytes."""
    result = {}
    address = 0
    for token in path.read_text().split():
        if token.startswith('@'):
            address = int(token[1:], 16) * 32
        else:
            for value in bytes.fromhex(token)[::-1]:
                result[address] = value
                address += 1
    return result


def prepare():
    case = OUT / 'case'
    command([str(PYTHON), 'tools/npu/gen_case.py', '--op', 'conv', '--seed', '1',
             '--width', '4', '--height', '1', '--cout', '16', '--out', str(case)],
            OUT / 'generate.log')
    original = {name: int(value, 16) for name, value in
                (line.split() for line in (case / 'regs.txt').read_text().splitlines())}
    # Fit the generated case into the existing 64 KiB DDR user-port model.
    # Descriptors contain relative offsets, so only region bases and image addresses move.
    bases = dict(DESC_BASE=0x1000, MODEL_BASE=0x2000, WORK_BASE=0x3000,
                 INPUT_BASE=0x4000, OUTPUT_BASE=0x5000)
    regs = original | bases
    (case / 'regs.txt').write_text(''.join(f'{k} {v:08x}\n' for k, v in regs.items()))
    memory = {}
    for region in ('desc', 'model', 'input'):
        name = region.upper() + '_BASE'
        path = case / f'mem_{region}.hex'
        delta = bases[name] - original[name]
        tokens = [f'@{int(token[1:], 16) + delta // 32:08x}'
                  if token.startswith('@') else token for token in path.read_text().split()]
        path.write_text('\n'.join(tokens) + '\n')
        memory.update(read_hex(path))
    _, address, size = (case / 'check.txt').read_text().split()
    address = int(address, 16) + bases['OUTPUT_BASE'] - original['OUTPUT_BASE']
    size = int(size, 16)
    (case / 'check.txt').write_text(f'output {address:08x} {size:08x}\n')
    command([str(PYTHON), 'tools/npu/ref/npu_ref.py', str(case)], OUT / 'reference.log')
    expected = read_hex(case / 'ref_out.hex')
    # A distinct fill makes an unwritten output byte fail the CPU comparison.
    memory.update({addr: expected[addr] ^ 0xff for addr in range(address, address + size)})
    with (OUT / 'ddr_bytes.hex').open('w') as output:
        for addr, value in sorted(memory.items()):
            output.write(f'@{addr:04x} {value:02x}\n')
    header = '/* Generated by verif/soc/board_npu/run.py; npu-spec 4. */\n'
    header += ''.join(f'#define NPU_CASE_{k} 0x{v:08x}u\n' for k, v in regs.items())
    header += f'#define NPU_CASE_OUTPUT_ADDRESS 0x{address:08x}u\n'
    header += f'static const unsigned char npu_expected[{size}] = {{\n'
    for start in range(address, address + size, 16):
        header += '    ' + ', '.join(f'0x{expected[addr]:02x}'
                                  for addr in range(start, min(start + 16, address + size))) + ',\n'
    (OUT / 'npu_case.h').write_text(header + '};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--prepare-only', action='store_true')
    parser.add_argument('--lint-only', action='store_true')
    args = parser.parse_args()
    sources = expand_files(HERE / 'files.f')
    common = ['--timing', '-Wall', '+define+SIM_MODE']
    command(['verilator', '--lint-only'] + common +
            ['--top-module', 'edrv32_fpga_board_npu_top'] + sources, OUT / 'lint_top.log')
    tb = common + ['--top-module', 'edrv32_board_npu_tb'] + sources
    command(['verilator', '--lint-only'] + tb, OUT / 'lint.log')
    if args.lint_only:
        print('PASS board_npu top and testbench lint, 0 warnings')
        return
    prepare()
    if args.prepare_only:
        print(f'PASS board_npu case/reference/header: {OUT}')
        return
    command(['make', '-C', 'sw', 'PROGRAM=bootloader'], OUT / 'bootloader.log')
    command(['make', '-C', 'sw', 'PROGRAM=board_npu_smoke'], OUT / 'software.log')
    rom = OUT / 'rom64.hex'
    sram = OUT / 'sram64.hex'
    pack_image(ROOT / 'build/sw/bootloader/rom.hex', 2048, rom)
    pack_image(ROOT / 'build/sw/board_npu_smoke/sram.hex', 8192, sram)
    obj = OUT / 'obj'
    command(['verilator', '--binary', '-j', '1', '-CFLAGS', '-O1', '--Mdir', str(obj),
             '-o', 'sim'] + tb, OUT / 'compile.log')
    start = time.monotonic()
    log = OUT / 'simulation.log'
    command([str(obj / 'sim'), '+ROM_HEX=' + str(rom), '+SRAM_HEX=' + str(sram),
             '+NPU_DDR_HEX=' + str(OUT / 'ddr_bytes.hex')], log)
    elapsed = time.monotonic() - start
    if PASS not in log.read_text():
        raise RuntimeError(f'{log}: missing PASS')
    print(f'PASS board_npu simulation={elapsed:.2f}s: {log}', flush=True)


if __name__ == '__main__':
    main()
