// ============================================================================
// File        : edrv32_axi_m2s_interconnect.v
// Description : Generic AXI4 multi-master/single-slave interconnect. Read and
//               write scheduling are independent.
// Notes       : Width conversion, CDC and target-specific protocol adaptation
//               are intentionally outside this module.
// ============================================================================

module edrv32_axi_m2s_interconnect #(
    parameter integer NUM_M = 4,
    parameter integer ADDR_W = 32,
    parameter integer DATA_W = 256,
    parameter integer ID_W = 4,
    parameter integer S_ID_W = 4,
    parameter integer LEN_W = 8,
    parameter integer WR_ORDER_DEPTH = 8,
    parameter integer STARVE_CYCLES = 64,
    parameter integer INGRESS_READY_BYPASS = 1,
    parameter integer MI_W = (NUM_M <= 1) ? 1 : $clog2(NUM_M),
    parameter integer COUNT_W = S_ID_W + 1
) (
    input  wire                         clk_i,
    input  wire                         rst_n_i,
    input  wire                         accept_i,

    input  wire [NUM_M*ID_W-1:0]        m_awid_i,
    input  wire [NUM_M*ADDR_W-1:0]      m_awaddr_i,
    input  wire [NUM_M*LEN_W-1:0]       m_awlen_i,
    input  wire [NUM_M*3-1:0]           m_awsize_i,
    input  wire [NUM_M*2-1:0]           m_awburst_i,
    input  wire [NUM_M*4-1:0]           m_awqos_i,
    input  wire [NUM_M-1:0]             m_awvalid_i,
    output wire [NUM_M-1:0]             m_awready_o,
    input  wire [NUM_M*DATA_W-1:0]      m_wdata_i,
    input  wire [NUM_M*(DATA_W/8)-1:0]  m_wstrb_i,
    input  wire [NUM_M-1:0]             m_wlast_i,
    input  wire [NUM_M-1:0]             m_wvalid_i,
    output wire [NUM_M-1:0]             m_wready_o,
    output wire [NUM_M*ID_W-1:0]        m_bid_o,
    output wire [NUM_M*2-1:0]           m_bresp_o,
    output wire [NUM_M-1:0]             m_bvalid_o,
    input  wire [NUM_M-1:0]             m_bready_i,

    input  wire [NUM_M*ID_W-1:0]        m_arid_i,
    input  wire [NUM_M*ADDR_W-1:0]      m_araddr_i,
    input  wire [NUM_M*LEN_W-1:0]       m_arlen_i,
    input  wire [NUM_M*3-1:0]           m_arsize_i,
    input  wire [NUM_M*2-1:0]           m_arburst_i,
    input  wire [NUM_M*4-1:0]           m_arqos_i,
    input  wire [NUM_M-1:0]             m_arvalid_i,
    output wire [NUM_M-1:0]             m_arready_o,
    output wire [NUM_M*ID_W-1:0]        m_rid_o,
    output wire [NUM_M*DATA_W-1:0]      m_rdata_o,
    output wire [NUM_M*2-1:0]           m_rresp_o,
    output wire [NUM_M-1:0]             m_rlast_o,
    output wire [NUM_M-1:0]             m_rvalid_o,
    input  wire [NUM_M-1:0]             m_rready_i,

    input  wire [NUM_M-1:0]             m_read_urgent_i,
    input  wire [NUM_M-1:0]             m_write_urgent_i,
    input  wire [NUM_M*4-1:0]           m_read_weight_i,
    input  wire [NUM_M*4-1:0]           m_write_weight_i,
    input  wire [NUM_M*5-1:0]           m_read_credit_i,
    input  wire [NUM_M*5-1:0]           m_write_credit_i,
    output wire [S_ID_W-1:0]            s_awid_o,
    output wire [ADDR_W-1:0]            s_awaddr_o,
    output wire [LEN_W-1:0]             s_awlen_o,
    output wire [2:0]                   s_awsize_o,
    output wire [1:0]                   s_awburst_o,
    output wire [3:0]                   s_awqos_o,
    output wire                         s_awvalid_o,
    input  wire                         s_awready_i,
    output wire [DATA_W-1:0]            s_wdata_o,
    output wire [DATA_W/8-1:0]          s_wstrb_o,
    output wire                         s_wlast_o,
    output wire                         s_wvalid_o,
    input  wire                         s_wready_i,
    input  wire [S_ID_W-1:0]            s_bid_i,
    input  wire [1:0]                   s_bresp_i,
    input  wire                         s_bvalid_i,
    output wire                         s_bready_o,

    output wire [S_ID_W-1:0]            s_arid_o,
    output wire [ADDR_W-1:0]            s_araddr_o,
    output wire [LEN_W-1:0]             s_arlen_o,
    output wire [2:0]                   s_arsize_o,
    output wire [1:0]                   s_arburst_o,
    output wire [3:0]                   s_arqos_o,
    output wire                         s_arvalid_o,
    input  wire                         s_arready_i,
    input  wire [S_ID_W-1:0]            s_rid_i,
    input  wire [DATA_W-1:0]            s_rdata_i,
    input  wire [1:0]                   s_rresp_i,
    input  wire                         s_rlast_i,
    input  wire                         s_rvalid_i,
    output wire                         s_rready_o,

    output wire [NUM_M*COUNT_W-1:0]     read_outstanding_o,
    output wire [NUM_M*COUNT_W-1:0]     write_outstanding_o,
    output wire                         read_protocol_error_o,
    output wire                         write_protocol_error_o,
    output wire                         write_owner_valid_o,
    output wire [MI_W-1:0]              write_owner_o
);

    edrv32_axi_m2s_read #(
        .NUM_M(NUM_M), .ADDR_W(ADDR_W), .DATA_W(DATA_W),
        .ID_W(ID_W), .S_ID_W(S_ID_W), .LEN_W(LEN_W),
        .STARVE_CYCLES(STARVE_CYCLES), .COUNT_W(COUNT_W),
        .INGRESS_READY_BYPASS(INGRESS_READY_BYPASS)
    ) u_read (
        .clk_i(clk_i), .rst_n_i(rst_n_i), .accept_i(accept_i),
        .m_arid_i(m_arid_i), .m_araddr_i(m_araddr_i),
        .m_arlen_i(m_arlen_i), .m_arsize_i(m_arsize_i),
        .m_arburst_i(m_arburst_i), .m_arqos_i(m_arqos_i),
        .m_arvalid_i(m_arvalid_i), .m_arready_o(m_arready_o),
        .m_rid_o(m_rid_o), .m_rdata_o(m_rdata_o),
        .m_rresp_o(m_rresp_o), .m_rlast_o(m_rlast_o),
        .m_rvalid_o(m_rvalid_o), .m_rready_i(m_rready_i),
        .m_read_urgent_i(m_read_urgent_i),
        .m_read_weight_i(m_read_weight_i),
        .m_read_credit_i(m_read_credit_i),
        .s_arid_o(s_arid_o), .s_araddr_o(s_araddr_o),
        .s_arlen_o(s_arlen_o), .s_arsize_o(s_arsize_o),
        .s_arburst_o(s_arburst_o), .s_arqos_o(s_arqos_o),
        .s_arvalid_o(s_arvalid_o), .s_arready_i(s_arready_i),
        .s_rid_i(s_rid_i), .s_rdata_i(s_rdata_i),
        .s_rresp_i(s_rresp_i), .s_rlast_i(s_rlast_i),
        .s_rvalid_i(s_rvalid_i), .s_rready_o(s_rready_o),
        .outstanding_o(read_outstanding_o),
        .protocol_error_o(read_protocol_error_o)
    );

    edrv32_axi_m2s_write #(
        .NUM_M(NUM_M), .ADDR_W(ADDR_W), .DATA_W(DATA_W),
        .ID_W(ID_W), .S_ID_W(S_ID_W), .LEN_W(LEN_W),
        .ORDER_DEPTH(WR_ORDER_DEPTH), .STARVE_CYCLES(STARVE_CYCLES),
        .MI_W(MI_W),
        .INGRESS_READY_BYPASS(INGRESS_READY_BYPASS),
        .COUNT_W(COUNT_W)
    ) u_write (
        .clk_i(clk_i), .rst_n_i(rst_n_i), .accept_i(accept_i),
        .m_awid_i(m_awid_i), .m_awaddr_i(m_awaddr_i),
        .m_awlen_i(m_awlen_i), .m_awsize_i(m_awsize_i),
        .m_awburst_i(m_awburst_i), .m_awqos_i(m_awqos_i),
        .m_awvalid_i(m_awvalid_i), .m_awready_o(m_awready_o),
        .m_wdata_i(m_wdata_i), .m_wstrb_i(m_wstrb_i),
        .m_wlast_i(m_wlast_i), .m_wvalid_i(m_wvalid_i),
        .m_wready_o(m_wready_o), .m_bid_o(m_bid_o),
        .m_bresp_o(m_bresp_o), .m_bvalid_o(m_bvalid_o),
        .m_bready_i(m_bready_i), .m_write_urgent_i(m_write_urgent_i),
        .m_write_weight_i(m_write_weight_i),
        .m_write_credit_i(m_write_credit_i),
        .s_awid_o(s_awid_o), .s_awaddr_o(s_awaddr_o),
        .s_awlen_o(s_awlen_o), .s_awsize_o(s_awsize_o),
        .s_awburst_o(s_awburst_o), .s_awqos_o(s_awqos_o),
        .s_awvalid_o(s_awvalid_o), .s_awready_i(s_awready_i),
        .s_wdata_o(s_wdata_o), .s_wstrb_o(s_wstrb_o),
        .s_wlast_o(s_wlast_o), .s_wvalid_o(s_wvalid_o),
        .s_wready_i(s_wready_i), .s_bid_i(s_bid_i),
        .s_bresp_i(s_bresp_i), .s_bvalid_i(s_bvalid_i),
        .s_bready_o(s_bready_o), .outstanding_o(write_outstanding_o),
        .protocol_error_o(write_protocol_error_o),
        .w_owner_valid_o(write_owner_valid_o),
        .w_owner_o(write_owner_o)
    );

endmodule
