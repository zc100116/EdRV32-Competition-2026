// ============================================================================
// File        : sram_axi.v
// Author      : Edward ZC
// Description : AXI4 Full slave for on-chip SRAM (design §6.5.1: 0x1000_0000,
//               256 KiB).  64-bit AXI endpoint: aggregated bursts use 8-byte
//               beats (two 32-bit storage words per beat, low lane first);
//               AxSIZE=4B narrow single transfers place data/strobes in the
//               byte lane selected by addr[2] (AXI narrow-transfer rule).
//               SIM_MODE selects a synchronous RTL word array; FPGA_MODE
//               selects the generated byte-enabled Pango DRM backend.
// Notes       : Verilog-2001.  Single ID, single outstanding.  Out-of-range,
//               unaligned, 4 KiB-crossing or narrow-burst accesses return
//               SLVERR, not silent wraparound.
// ============================================================================
`include "edrv32_axi4.vh"
`include "edrv32_build_mode.vh"

// ============================================================================
// sram_axi - AXI4 SRAM slave (byte-strobed, burst read, 64-bit endpoint)
// ============================================================================
module sram_axi #(
    parameter NUM_WORDS = 65536,               // 32-bit words (256 KiB)
    parameter [31:0] BASE_ADDR = 32'h1000_0000,
    parameter ID_W = `AXI_ID_W,                // global ID width from fabric
    parameter SRAM_INIT_FILE = ""
)(
    // --- Clock and reset ---
    input  wire                     clk,
    input  wire                     rst_n,

    // --- AXI4 write address channel ---
    input  wire [ID_W-1:0]          awid_i,
    input  wire [31:0]              awaddr_i,
    input  wire [`AXI_LEN_W-1:0]    awlen_i,
    input  wire [`AXI_SIZE_W-1:0]   awsize_i,
    input  wire [`AXI_BURST_W-1:0]  awburst_i,
    input  wire                     awvalid_i,
    output wire                     awready_o,
    // --- AXI4 write data channel ---
    input  wire [`AXI_DATA_W-1:0]   wdata_i,
    input  wire [`AXI_STRB_W-1:0]   wstrb_i,
    input  wire                     wlast_i,
    input  wire                     wvalid_i,
    output wire                     wready_o,
    // --- AXI4 write response channel ---
    output wire [ID_W-1:0]          bid_o,
    output wire [`AXI_RESP_W-1:0]   bresp_o,
    output wire                     bvalid_o,
    input  wire                     bready_i,
    // --- AXI4 read address channel ---
    input  wire [ID_W-1:0]          arid_i,
    input  wire [31:0]              araddr_i,
    input  wire [`AXI_LEN_W-1:0]    arlen_i,
    input  wire [`AXI_SIZE_W-1:0]   arsize_i,
    input  wire [`AXI_BURST_W-1:0]  arburst_i,
    input  wire                     arvalid_i,
    output wire                     arready_o,
    // --- AXI4 read data channel ---
    output wire [ID_W-1:0]          rid_o,
    output wire [`AXI_DATA_W-1:0]   rdata_o,
    output wire [`AXI_RESP_W-1:0]   rresp_o,
    output wire                     rlast_o,
    output wire                     rvalid_o,
    input  wire                     rready_i
);

    localparam IDX_W = $clog2(NUM_WORDS);
    localparam PAIR_WORDS = (NUM_WORDS + 1) / 2;
    localparam PAIR_IDX_W = $clog2(PAIR_WORDS);

    // ------------------------------------------------------------------
    // Synchronous 64-bit storage backend.
    // ------------------------------------------------------------------
    wire [63:0] storage_rd_data_w;
    wire [PAIR_IDX_W-1:0] storage_rd_addr_w;
    wire [PAIR_IDX_W-1:0] storage_wr_addr_w;
    wire [63:0] storage_wr_data_w;
    wire [7:0] storage_wr_strb_w;
    wire storage_wr_en_w;

    reg [ID_W-1:0] rid_r;
    reg [ID_W-1:0] bid_r;
    reg r_err_r;
    reg b_err_r;
    reg        rvalid_r;
    reg        rlast_r;
    reg        r_wide_r;
    reg        r_high_lane_r;
    reg [IDX_W-1:0] r_word_r;            // low storage word of the next beat
    reg [`AXI_LEN_W-1:0] r_beats_left_r;
    reg [IDX_W-1:0] w_word_r;            // low storage word of the current beat
    reg        w_wide_r;
    reg [`AXI_LEN_W-1:0] w_beats_left_r;
    reg        bvalid_r;
    reg rd_busy_r;
    reg wr_busy_r;

    wire [31:0] END_ADDR_W  = BASE_ADDR + NUM_WORDS * 4;
    // Burst byte count: (len+1) x (8B wide beat | 4B narrow beat).
    wire [14:0] rd_blen_w = arsize_i[0] ? ({7'b0, arlen_i} << 3)
                                        : ({7'b0, arlen_i} << 2);
    wire [14:0] wr_blen_w = awsize_i[0] ? ({7'b0, awlen_i} << 3)
                                        : ({7'b0, awlen_i} << 2);
    wire [31:0] rd_last_addr_w = araddr_i + {17'b0, rd_blen_w};
    wire [31:0] wr_last_addr_w = awaddr_i + {17'b0, wr_blen_w};
    wire [14:0] rd_end_off_w = {3'b000, araddr_i[11:0]} + rd_blen_w +
                               (arsize_i[0] ? 15'd8 : 15'd4);
    // A legal wide beat is 8-byte aligned.  Therefore a burst crosses a
    // 4 KiB page exactly when start_beat_in_page + LEN carries out of the
    // nine-bit page beat index.  A legal narrow request is one 4-byte beat
    // and cannot cross the page.  This is equivalent to the former
    // page_offset + burst_bytes + beat_bytes comparison, but removes a
    // duplicate 15-bit adder from the AW acceptance path; wr_last_addr_w
    // remains the single address result for memory-range and overflow checks.
    wire [9:0] wr_last_page_beat_w = {1'b0, awaddr_i[11:3]} +
                                     {2'b00, awlen_i};
    // Narrow (4B) transfers are single-beat only; wide (8B) beats must be
    // aligned to the 8-byte lane grid (addr[2]==0).
    wire rd_size_ok_w = (arsize_i == `AXI_SIZE_8B) ||
                        ((arsize_i == `AXI_SIZE_4B) && (arlen_i == 0));
    wire wr_size_ok_w = (awsize_i == `AXI_SIZE_8B) ||
                        ((awsize_i == `AXI_SIZE_4B) && (awlen_i == 0));
    wire read_req_err_w = (araddr_i < BASE_ADDR)
                          || (rd_last_addr_w >= END_ADDR_W)
                          || (rd_last_addr_w < araddr_i)
                          || (araddr_i[1:0] != 2'b00)
                          || (araddr_i[2] && (arsize_i == `AXI_SIZE_8B))
                          || !rd_size_ok_w
                          || (arburst_i != `AXI_BURST_INCR)
                          || (rd_end_off_w > 15'd4096);
    wire write_req_err_w = (awaddr_i < BASE_ADDR)
                           || (wr_last_addr_w >= END_ADDR_W)
                           || (wr_last_addr_w < awaddr_i)
                           || (awaddr_i[1:0] != 2'b00)
                           || (awaddr_i[2] && (awsize_i == `AXI_SIZE_8B))
                           || !wr_size_ok_w
                           || (awburst_i != `AXI_BURST_INCR)
                           || ((awsize_i == `AXI_SIZE_8B) &&
                               wr_last_page_beat_w[9]);

    // 8-byte beat: {mem[w+1], mem[w]}.  4-byte narrow beat: the storage word
    // placed in the addr[2] byte lane.
    wire [IDX_W-1:0] rd_next_word_w =
        r_word_r + {{(IDX_W-2){1'b0}}, 2'b10};
    wire [PAIR_IDX_W-1:0] rd_next_pair_w =
        rd_next_word_w[IDX_W-1:1];
    wire [IDX_W-1:0] ar_lo_word_w = araddr_i[IDX_W+1:2];
    wire [PAIR_IDX_W-1:0] ar_pair_w = ar_lo_word_w[IDX_W-1:1];
    wire [PAIR_IDX_W-1:0] w_pair_w = w_word_r[IDX_W-1:1];

    // ------------------------------------------------------------------
    // Read channel: AR latch -> stream R beats (fetch next beat word pair
    // on each R accept).
    // ------------------------------------------------------------------
    assign arready_o = !rd_busy_r;
    wire ar_fire_w = arvalid_i && arready_o;
    wire r_fire_w  = rvalid_r && rready_i;

    assign storage_rd_addr_w = ar_fire_w ? ar_pair_w :
                               ((r_fire_w && !rlast_r) ? rd_next_pair_w :
                                r_word_r[IDX_W-1:1]);

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            rd_busy_r      <= 1'b0;
            rvalid_r       <= 1'b0;
            rlast_r        <= 1'b0;
            r_wide_r       <= 1'b0;
            r_high_lane_r  <= 1'b0;
            r_err_r        <= 1'b0;
            rid_r          <= {ID_W{1'b0}};
            r_word_r       <= {IDX_W{1'b0}};
            r_beats_left_r <= {`AXI_LEN_W{1'b0}};
        end else if (ar_fire_w) begin
            rd_busy_r      <= 1'b1;
            rid_r          <= arid_i;
            r_word_r       <= ar_lo_word_w;
            r_beats_left_r <= arlen_i;
            r_err_r        <= read_req_err_w;
            r_wide_r       <= (arsize_i == `AXI_SIZE_8B);
            r_high_lane_r  <= araddr_i[2];
            rvalid_r       <= 1'b1;
            rlast_r        <= (arlen_i == 0);
        end else if (r_fire_w) begin
            if (rlast_r) begin
                rvalid_r  <= 1'b0;
                rd_busy_r <= 1'b0;
            end else begin
                r_beats_left_r <= r_beats_left_r - 1'b1;
                r_word_r       <= rd_next_word_w;
                rlast_r        <= (r_beats_left_r == 1);
            end
        end
    end

    assign rvalid_o = rvalid_r;
    assign rdata_o  = r_err_r ? {`AXI_DATA_W{1'b0}} :
                      (r_wide_r ? storage_rd_data_w :
                       (r_high_lane_r ? {storage_rd_data_w[63:32], 32'h0}
                                          : {32'h0, storage_rd_data_w[31:0]}));
    assign rresp_o  = r_err_r ? `AXI_RESP_SLVERR : `AXI_RESP_OKAY;
    assign rlast_o  = rlast_r;
    assign rid_o    = rid_r;

    // ------------------------------------------------------------------
    // Write channel: AW latch -> W beats committed as they arrive -> B.
    // ------------------------------------------------------------------
    assign awready_o = !wr_busy_r && !bvalid_r;
    wire aw_fire_w = awvalid_i && awready_o;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            wr_busy_r      <= 1'b0;
            bvalid_r       <= 1'b0;
            b_err_r        <= 1'b0;
            bid_r          <= {ID_W{1'b0}};
            w_word_r       <= {IDX_W{1'b0}};
            w_wide_r       <= 1'b0;
            w_beats_left_r <= {`AXI_LEN_W{1'b0}};
        end else begin
            if (aw_fire_w) begin
                wr_busy_r      <= 1'b1;
                bid_r          <= awid_i;
                w_word_r       <= awaddr_i[IDX_W+1:2];
                w_wide_r       <= (awsize_i == `AXI_SIZE_8B);
                w_beats_left_r <= awlen_i;
                b_err_r        <= write_req_err_w;
            end

            // Write data beats: commit as they arrive (byte strobes per
            // storage word; narrow single writes use the addr[2] lane).
            // AXI allows W beats to complete while B is pending — do not
            // gate W acceptance on bvalid_r (a pending B must not block W).
            if (wr_busy_r && wvalid_i && wready_o) begin
                if (wlast_i != (w_beats_left_r == 0))
                    b_err_r <= 1'b1;
                if (wlast_i || (w_beats_left_r == 0)) begin
                    bvalid_r <= 1'b1;
                end else begin
                    w_word_r       <= w_word_r
                                      + {{(IDX_W-2){1'b0}}, 2'b10};
                    w_beats_left_r <= w_beats_left_r - 1'b1;
                end
            end

            if (bvalid_r && bready_i) begin
                bvalid_r  <= 1'b0;
                wr_busy_r <= 1'b0;
            end
        end
    end

    assign bvalid_o = bvalid_r;
    assign bid_o    = bid_r;
    assign bresp_o  = b_err_r ? `AXI_RESP_SLVERR : `AXI_RESP_OKAY;
    assign wready_o = wr_busy_r && !bvalid_r;

    assign storage_wr_addr_w = w_pair_w;
    assign storage_wr_data_w = wdata_i;
    assign storage_wr_strb_w = w_wide_r ? wstrb_i :
                               (w_word_r[0] ? {wstrb_i[7:4], 4'h0}
                                            : {4'h0, wstrb_i[3:0]});
    assign storage_wr_en_w = wr_busy_r && wvalid_i && wready_o && !b_err_r;

`ifdef EDRV32_BUILD_MODE_CONFLICT
    edrv32_build_mode_error__define_only_one_of_FPGA_MODE_or_SIM_MODE
        u_build_mode_error ();
`elsif EDRV32_FPGA_MEMORY_MODE
    pango_sram_storage #(
        .PAIR_ADDR_W (PAIR_IDX_W)
    ) u_pango_sram_storage (
        .clk       (clk),
        .rst_n     (rst_n),
        .rd_addr_i (storage_rd_addr_w),
        .rd_data_o (storage_rd_data_w),
        .wr_addr_i (storage_wr_addr_w),
        .wr_data_i (storage_wr_data_w),
        .wr_strb_i (storage_wr_strb_w),
        .wr_en_i   (storage_wr_en_w)
    );

`else
    sram_storage #(
        .ADDR_W (PAIR_IDX_W),
        .DEPTH  (PAIR_WORDS),
        .INIT_FILE(SRAM_INIT_FILE)
    ) u_sram_storage (
        .clk       (clk),
        .rd_addr_i (storage_rd_addr_w),
        .rd_data_o (storage_rd_data_w),
        .wr_addr_i (storage_wr_addr_w),
        .wr_data_i (storage_wr_data_w),
        .wr_strb_i (storage_wr_strb_w),
        .wr_en_i   (storage_wr_en_w)
    );
`endif

endmodule
