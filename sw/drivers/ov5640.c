/* Design 3.2: expose the exact table used for both cameras and its actual entry count. */
const struct ov5640_register *ov5640_table(size_t *count)
{
    *count = sizeof(registers) / sizeof(registers[0]);
    return registers;
}

/* Vendor camera.v: CLINT cycles implement sensor power/reset delays, not timeout recovery. */
static void sensor_delay(uint32_t clock_hz, uint32_t microseconds)
{
    uint64_t cycles = (uint64_t)clock_hz * microseconds / 1000000u;
    uint64_t start = clint_time();
    while (clint_time() - start < cycles) {
    }
}

/* SoC 3.5: preserve LEDs and the other camera's output and direction bits. */
int ov5640_init(unsigned int camera, uint32_t clock_hz)
{
    uint32_t pwdn = 1u << (12u + 2u * camera);
    uint32_t reset = 1u << (13u + 2u * camera);
    uint32_t output = mmio_read32(EDRV32_GPIO0_BASE + GPIO_OUT);
    uint32_t enable = mmio_read32(EDRV32_GPIO0_BASE + GPIO_OE);
    gpio_write((uint16_t)((output | pwdn) & ~reset));
    gpio_set_output_enable((uint16_t)(enable | pwdn | reset));
    sensor_delay(clock_hz, 5000u);
    gpio_write((uint16_t)(output & ~(pwdn | reset)));
    sensor_delay(clock_hz, 1300u);
    gpio_write((uint16_t)((output & ~pwdn) | reset));
    sensor_delay(clock_hz, 21000u);
    i2c_init(camera, clock_hz, 100000u);
    for (size_t i = 0; i < sizeof(registers) / sizeof(registers[0]); ++i) {
        if (i2c_sccb_write(0x3cu, registers[i].address, registers[i].value) != 0) {
            return -1;
        }
    }
    return 0;
}

/* Design 3.2; legacy cam.c: chip ID is high byte at 0x300a then low byte at 0x300b. */
int ov5640_chip_id(unsigned int camera, uint32_t clock_hz, uint16_t *chip_id)
{
    uint8_t high;
    uint8_t low;
    i2c_init(camera, clock_hz, 100000u);
    if (i2c_sccb_read(0x3cu, 0x300au, &high) != 0) {
        return -1;
    }
    if (i2c_sccb_read(0x3cu, 0x300bu, &low) != 0) {
        return -1;
    }
    *chip_id = (uint16_t)(((uint16_t)high << 8) | low);
    return 0;
}
