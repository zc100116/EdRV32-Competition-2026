#!/usr/bin/env python3
"""tech 5b/7: subset the licensed 12px BDF into CPU glyph rows (stdlib).

Glyph rows are native pixels, not GPU-resident atlases. The renderer caches only
the glyphs needed by the current interface. No fallback font is substituted.
"""
import argparse
import csv
import pathlib
import re

APP = pathlib.Path(__file__).resolve().parents[1]
SOURCE = APP / 'assets/fonts/fusion-pixel-12px-monospaced-zh_hans.bdf'
HEIGHT = 12
ASCENT = 10
# Original native-pixel mathematical minus used by the Chinese item tables.
# This is an explicit glyph in the Ember UI set, not missing-character fallback.
SYMBOLS = {0x2212: (6, [0, 0, 0, 0, 0, 0x780, 0, 0, 0, 0, 0, 0])}


def required_characters():
    characters = set(map(chr, range(32, 127)))
    for path in sorted((APP / 'data').glob('*.csv')):
        with path.open(newline='', encoding='utf-8') as stream:
            for row in csv.reader(stream):
                for value in row:
                    characters.update(c for c in value if c.isprintable())
    # A single lexer keeps comments out without mistaking quoted // for comments.
    tokens = re.compile(r'("(?:\\.|[^"\\])*")|/\*.*?\*/|//[^\n]*', re.S)
    paths = [APP / 'src/game.c']
    for directory in ('ui', 'meta', 'gfx2d'):
        paths.extend(sorted((APP / 'src' / directory).glob('*.c')))
        paths.extend(sorted((APP / 'src' / directory).glob('*.h')))
        paths.extend(sorted((APP / 'src' / directory).glob('*.inc')))
    for path in paths:
        for token in tokens.finditer(path.read_text(encoding='utf-8')):
            if token.group(1):
                characters.update(c for c in token.group(1) if c.isprintable())
    return set(map(ord, characters))


def read_glyphs(required):
    glyphs = {}
    with SOURCE.open(encoding='utf-8') as stream:
        for line in stream:
            if line.startswith('ENCODING '):
                codepoint = int(line.split()[1])
            elif line.startswith('DWIDTH '):
                advance = int(line.split()[1])
            elif line.startswith('BBX '):
                width, height, left, bottom = map(int, line.split()[1:])
            elif line.strip() == 'BITMAP':
                bitmap = []
                for line in stream:
                    if line.strip() == 'ENDCHAR':
                        break
                    bitmap.append(line.strip())
                if codepoint not in required:
                    continue
                rows = [0] * HEIGHT
                top = ASCENT - bottom - height
                for y, row in enumerate(bitmap):
                    bits = int(row, 16)
                    for x in range(width):
                        if bits & (1 << (len(row) * 4 - 1 - x)):
                            rows[top + y] |= 1 << (11 - left - x)
                glyphs[codepoint] = advance, rows
    glyphs.update({code: glyph for code, glyph in SYMBOLS.items() if code in required})
    missing = sorted(required - glyphs.keys())
    if missing:
        raise ValueError('Fusion Pixel lacks required UI glyphs: ' + ', '.join(
            f'U+{code:04X} {chr(code)!r}' for code in missing))
    return glyphs


def convert(output):
    glyphs = read_glyphs(required_characters())
    lines = ['/* Generated by ember_isles/tools/font_convert.py; CPU data only. */',
             '#ifndef EMBER_FONT_H', '#define EMBER_FONT_H', '#include <stdint.h>',
             '#define EMBER_FONT_HEIGHT 12u', '#define EMBER_FONT_ASCENT 10u',
             f'#define EMBER_FONT_GLYPHS {len(glyphs)}u',
             '/* Bit 11 is the leftmost pixel; rows share the 12px line box.',
             ' * Advance is 6px for Latin and 12px for fullwidth glyphs.',
             ' * Codepoints are sorted for lookup; no full font enters GPU RAM. */',
             'struct ember_font_glyph {', '    uint32_t codepoint;',
             '    uint8_t advance;', '    uint16_t rows[EMBER_FONT_HEIGHT];', '};',
             'static const struct ember_font_glyph ember_font[EMBER_FONT_GLYPHS] = {']
    for codepoint, (advance, rows) in sorted(glyphs.items()):
        values = ','.join(f'0x{row:03x}' for row in rows)
        lines.append(f'    {{0x{codepoint:x}u,{advance}u,{{{values}}}}},')
    lines.extend(['};', '#endif', ''])
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text('\n'.join(lines), encoding='utf-8')
    print(f'CPU font subset: {len(glyphs)} glyphs; '
          f'{len(glyphs) * HEIGHT * 2} bitmap bytes; GPU bytes: 0 (not uploaded)')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=pathlib.Path,
                        default=APP.parents[2] / 'build/ember_isles/generated/font.h')
    convert(parser.parse_args().output)


if __name__ == '__main__':
    main()
