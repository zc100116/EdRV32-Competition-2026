/* ddr_map.h — showcase 4.5.4; frozen physical DDR offsets (not CPU aliases). */
#ifndef SHOWCASE_DDR_MAP_H
#define SHOWCASE_DDR_MAP_H
#define SHOWCASE_MODEL_BASE 0x09000000u
#define SHOWCASE_MODEL_BYTES 0x01000000u
#define SHOWCASE_IMAGE_BASE 0x08000000u
#define SHOWCASE_IMAGE_SLOT1_BASE 0x08200000u
#define SHOWCASE_IMAGE_BYTES 0x00200000u
#define SHOWCASE_UPLOAD_BASE 0x0b000000u
#define SHOWCASE_UPLOAD_BYTES 0x00800000u
#define SHOWCASE_INPUT_BASE 0x0a010000u
#define SHOWCASE_MESSAGE_BASE 0x0a011000u
#define SHOWCASE_MESSAGE_BYTES 1024u
#define SHOWCASE_TX_DESC 0x0a100000u
#define SHOWCASE_TX_DATA 0x0a100800u
#define SHOWCASE_MONITOR_RING 0x0a102000u
#define SHOWCASE_VISION_TX_DESC 0x0a180000u
#define SHOWCASE_VISION_EDDT 0x0a180200u
#define SHOWCASE_VISION_GEO_DESC 0x0a180700u
/* PIPE-SPEC 3.3: 13 groups (source + 12 hops), three 2 MiB slots each.
 * [0x14000000,0x18e00000) follows the 64 MiB application window.
 * Control/thumbnail storage occupies [0x18e00000,0x18f00000).
 */
#define SHOWCASE_PIPE_BASE 0x14000000u
#define SHOWCASE_PIPE_SLOT_BYTES 0x00200000u
#define SHOWCASE_PIPE_CONTROL 0x18e00000u
#define SHOWCASE_PIPE_GEO_DESC SHOWCASE_PIPE_CONTROL
#define SHOWCASE_PIPE_RND_DESC (SHOWCASE_PIPE_CONTROL + 0x1000u)
#define SHOWCASE_PIPE_THUMB_BASE (SHOWCASE_PIPE_CONTROL + 0x10000u)
#endif
