#define VISION_INPUT_BYTES 983040u
#define VISION_OUTPUT_BASE 0x05000000u
#define VISION_POST_BASE 0x05100000u
#define VISION_POST_SPACING 0x00020000u
#define VISION_POST_TX 0x05140000u
#define VISION_OUTPUT_BYTES 725760u
#define VISION_IMAGE_BASE 0x06000000u
#define VISION_IMAGE_SPACING 0x00200000u
#define VISION_GEO_BASE 0x07000000u
#define VISION_WIDTH 1280u
#define VISION_HEIGHT 720u
#define VISION_STRIDE 2560u
#define VISION_IMAGE_BYTES 1843200u
#define VISION_SEND_BASE 0x0a180000u
#define VISION_TX_DESCRIPTORS VISION_SEND_BASE
#define VISION_TX_DETECTIONS (VISION_SEND_BASE + 0x200u)
#define VISION_GEO_DESCRIPTOR (VISION_SEND_BASE + 0x700u)
#endif
