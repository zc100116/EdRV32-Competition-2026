#!/usr/bin/env python3
# File: gen_recip_q30.py
# Spec: gpu-spec 2.12; gpu microarchitecture 4.8.
# Description: Generate the Q30 midpoint seed's DRM image and exact low-bit LUTROM.
# Clock domain: host tool.
"""Generate fixed 1024-entry Q30 reciprocal seeds, without floating point."""
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[3]
    seeds = []
    for index in range(1024):
        midpoint = (1 << 30) + (index << 20) + (1 << 19)
        seeds.append(((1 << 60) + midpoint // 2) // midpoint)
    (root / 'fpga/ip/gpu_recip_q30.dat').write_text(
        ''.join(f'{value >> 12:05x}\n' for value in seeds))
    lines = [
        '// File: edrv32_rom_gpu_recip_q30.v',
        '// Spec: gpu-spec 2.12; GPU microarchitecture 4.8.',
        '// Description: Exact Q30 midpoint seeds; high 18 bits in one DRM,',
        '//              low 12 bits in a constant LUTROM, both enabled with one-cycle latency.',
        '// Clock domain: clk_gpu.',
        '// Generated by tools/gpu/rom/gen_recip_q30.py.',
        '`include "edrv32_build_mode.vh"',
        'module edrv32_rom_gpu_recip_q30 (',
        '    // Memory clock.',
        '    input wire clk_i,',
        '',
        '    // Enabled synchronous seed read.',
        '    input wire en_i,',
        '    input wire [9:0] addr_i,',
        '    output wire [29:0] rd_data_o',
        ');',
        '    wire [17:0] high_w;',
        '    reg [11:0] low_w;',
        '    reg [11:0] low_r;',
        '',
        '    assign rd_data_o = {high_w, low_r};',
        '',
        '    always @(*) begin',
        "        low_w = 12'd0;",
        '        case (addr_i)',
    ]
    lines += [f"            10'd{i}: low_w = 12'h{seed & 4095:03x};"
              for i, seed in enumerate(seeds)]
    lines += [
        "            default: low_w = 12'd0;",
        '        endcase',
        '    end',
        '',
        '    always @(posedge clk_i) begin',
        '        if (en_i) begin',
        '            low_r <= low_w;',
        '        end',
        '    end',
        '',
        '`ifdef EDRV32_FPGA_MEMORY_MODE',
        '    ip_rom_gpu_recip_q30 u_ip (',
        '        .clk(clk_i),',
        '        .clk_en(en_i),',
        "        .rst(1'b0),",
        '        .addr(addr_i),',
        '        .rd_data(high_w)',
        '    );',
        '`else',
        '    reg [17:0] memory_r [0:1023];',
        '    reg [17:0] high_r;',
        '',
        '    assign high_w = high_r;',
        '',
        '    initial begin',
        '        $readmemh("fpga/ip/gpu_recip_q30.dat", memory_r);',
        '    end',
        '',
        '    always @(posedge clk_i) begin',
        '        if (en_i) begin',
        '            high_r <= memory_r[addr_i];',
        '        end',
        '    end',
        '`endif',
        'endmodule',
    ]
    (root / 'rtl/tech/edrv32_rom_gpu_recip_q30.v').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
