#!/usr/bin/env python3
"""gen_codec.py — gpu-spec 2–4 record codecs using the generated BSP constants.
Host utility, no clock domain. Regenerate codec.h after changing gpu.json.
"""
from pathlib import Path
import sys
sys.dont_write_bytecode = True
import textwrap
sys.path.insert(0, str(Path(__file__).resolve().parents[3]))
from tools.gpu.scene import SCHEMA, SIGNED, BYTE_FIELDS
out = ['/* codec.h — gpu-spec 2–4; generated by gen_codec.py; host, no clock. */',
       '#ifndef GPU_EMU_CODEC_H', '#define GPU_EMU_CODEC_H',
       '#include "../../../sw/bsp/include/regs/gpu_regs.h"',
       'struct register_desc { const char *name; uint32_t offset, reset, mask; int access; };',
       'static const struct register_desc register_descs[] = {']
for reg in SCHEMA['registers']:
    name = reg['name']
    prefix = 'EDRV32_GPU_' + name
    mask = ' | '.join(prefix+'_'+f['name']+'_MASK' for f in reg['fields']) or 'UINT32_MAX'
    for i in range(reg['dimensions'][0]['count'] if reg['dimensions'] else 1):
        suffix = f'[{i}]' if reg['dimensions'] else ''
        offset = prefix+f'_OFFSET({i})' if suffix else prefix+'_OFFSET'
        access = {'RO': 0, 'RW': 1, 'RW1C': 2, 'WO': 3}[reg['access']]
        out.append(f'    {{"{name}{suffix}", {offset}, {prefix}_RESET, {mask}, {access}}},')
out += ['};', 'static inline uint32_t load32(const uint8_t *p)', '{',
        '    return (uint32_t)p[0] | (uint32_t)p[1]<<8 | (uint32_t)p[2]<<16',
        '        | (uint32_t)p[3]<<24;', '}',
        'static inline void store32(uint8_t *p, uint32_t v)', '{',
        '    for (int i = 0; i < 4; ++i) p[i] = (uint8_t)(v >> (8*i));', '}',
        'static inline int64_t sign_bits(uint32_t v, unsigned bits)', '{',
        '    return (int64_t)(v & ((UINT64_C(1)<<bits)-1))',
        '        - ((v & (UINT64_C(1)<<(bits-1))) ? (INT64_C(1)<<bits) : 0);', '}']
for layout in SCHEMA['layouts']:
    name = layout['name']
    fields = [f for f in layout['fields'] if f['name'] != 'OPCODE']
    if not fields:
        continue
    out += [f'struct {name.lower()} {{']
    out += [f'    int64_t {f["name"].lower()};' for f in fields]
    out += ['};', f'static inline struct {name.lower()} decode_{name.lower()}(const uint8_t *p)',
            '{', f'    struct {name.lower()} v;']
    for f in fields:
        n = f['name']; pre = f'EDRV32_GPU_{name}_{n}'
        expr = f'(load32(p + {pre}_OFFSET) & {pre}_MASK)'
        if n not in BYTE_FIELDS:
            expr += f' >> {pre}_POS'
        if n in SIGNED:
            expr = f'sign_bits({expr}, {pre}_WIDTH)'
        out += [f'    v.{n.lower()} = {expr};']
    out += ['    return v;', '}']
    if name == 'OBJ':
        out += ['static inline void update_obj(uint8_t *p, struct obj v)', '{']
        for f in fields:
            n=f['name']; pre=f'EDRV32_GPU_OBJ_{n}'
            if n not in ('ALIVE','PX','PY','VX','VY','LIFE'): continue
            out += [f'    store32(p + {pre}_OFFSET,',
                    f'        (load32(p + {pre}_OFFSET) & ~{pre}_MASK)',
                    f'        | (((uint32_t)v.{n.lower()} << {pre}_POS) & {pre}_MASK));']
        out += ['}']
out += ['#endif']
lines = [part for line in out for part in textwrap.wrap(
    line, width=96, subsequent_indent='        ', break_long_words=False,
    break_on_hyphens=False) or ['']]
Path(__file__).with_name('codec.h').write_text('\n'.join(lines)+'\n')

from tools.gpu.model.arithmetic import logarithm_entry
rom = ['/* log_rom.h — gpu-spec 2.6 integer log2 ROM; host, no clock. */',
       'static const int log_rom[256] = {']
for j in range(0, 256, 16):
    rom.append('    ' + ', '.join(str(logarithm_entry(i)) for i in range(j,j+16)) + ',')
rom.append('};')
Path(__file__).with_name('log_rom.h').write_text('\n'.join(rom)+'\n')
