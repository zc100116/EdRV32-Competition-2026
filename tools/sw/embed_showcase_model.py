#!/usr/bin/env python3
"""Showcase P5b 9.1: read compiler hex like debug_tool/core/yolo.py; host clock.
Generate immutable C arrays for the BIOS-loaded ELF using only the standard library.
"""
import argparse
from pathlib import Path


def read_hex(path, base):
    data = bytearray()
    address = base
    for token in path.read_text(encoding='ascii').split():
        if token.startswith('@'):
            address = int(token[1:], 16) * 32
        else:
            chunk = bytes.fromhex(token)[::-1]
            offset = address - base
            if offset > len(data):
                data.extend(bytes(offset - len(data)))
            data[offset:offset + len(chunk)] = chunk
            address += len(chunk)
    return data


def generate(directory, output):
    regs = {key: int(value, 16) for key, value in
            (line.split() for line in (directory / 'regs.txt').read_text().splitlines())}
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='ascii') as source:
        source.write('/* Generated by tools/sw/embed_showcase_model.py. */\n#include <stdint.h>\n')
        source.write(f'const uint32_t showcase_model_count = {regs["DESC_COUNT"]};\n')
        for name, filename, base in [('desc', 'mem_desc.hex', 'DESC_BASE'),
                                     ('weights', 'mem_model.hex', 'MODEL_BASE')]:
            data = read_hex(directory / filename, regs[base])
            source.write(f'const uint32_t showcase_model_{name}_bytes = {len(data)};\n')
            source.write(f'const uint8_t showcase_model_{name}[] = {{\n')
            for offset in range(0, len(data), 16):
                values = ','.join(f'0x{x:02x}' for x in data[offset:offset+16])
                source.write('    ' + values + ',\n')
            source.write('};\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    generate(args.directory, args.output)
