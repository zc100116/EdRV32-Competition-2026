#!/usr/bin/env python3
"""Showcase P5b 9.1: read compiler hex like debug_tool/core/yolo.py; host clock.
Generate immutable C arrays for the BIOS-loaded ELF using only the standard library.
"""
import argparse
import json
import sys
from pathlib import Path


def read_hex(path, base):
    data = bytearray()
    address = base
    for token in path.read_text(encoding='ascii').split():
        if token.startswith('@'):
            address = int(token[1:], 16) * 32
        else:
            chunk = bytes.fromhex(token)[::-1]
            offset = address - base
            if offset > len(data):
                data.extend(bytes(offset - len(data)))
            data[offset:offset + len(chunk)] = chunk
            address += len(chunk)
    return data


def generate(directory, output, pose_quantization=None):
    prefix = "showcase_pose" if pose_quantization else "showcase_model"
    regs = {key: int(value, 16) for key, value in
            (line.split() for line in (directory / 'regs.txt').read_text().splitlines())}
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', encoding='ascii') as source:
        source.write('/* Generated by tools/sw/embed_showcase_model.py. */\n#include <stdint.h>\n')
        source.write(f'const uint32_t {prefix}_count = {regs["DESC_COUNT"]};\n')
        for name, filename, base in [('desc', 'mem_desc.hex', 'DESC_BASE'),
                                     ('weights', 'mem_model.hex', 'MODEL_BASE')]:
            data = read_hex(directory / filename, regs[base])
            source.write(f'const uint32_t {prefix}_{name}_bytes = {len(data)};\n')
            source.write(f'const uint8_t {prefix}_{name}[] = {{\n')
            for offset in range(0, len(data), 16):
                values = ','.join(f'0x{x:02x}' for x in data[offset:offset+16])
                source.write('    ' + values + ',\n')
            source.write('};\n')

        if pose_quantization:
            sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'npu'))
            from fixed_plan import build_plan
            from yolo_post_ref import make_heads
            quant = json.loads(pose_quantization.read_text())
            source.write('#include "pose.h"\n')
            source.write('const yolo_head showcase_pose_heads[3] = {\n')
            for head in make_heads(quant):
                source.write('    {\n')
                for key, value in head.items():
                    if isinstance(value, list):
                        value = '{' + ','.join(map(str, value)) + '}'
                    source.write(f'        .{key} = {value},\n')
                source.write('    },\n')
            source.write('};\nconst struct pose_head showcase_pose_keypoints[3] = {\n')
            rows = {row['name']: row for row in quant['convolutions']}
            plan = build_plan('pose')
            for i in range(3):
                tensor = plan['tensors'][f'D{i}.kpt']
                row = rows[f'D{i}.kpt.out']
                source.write('    {%d, %.17gf, %d},\n' % (
                    tensor['base'] - 0x05000000, row['output_scale'],
                    row['output_zero_point']))
            source.write('};\n')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--pose-quantization', type=Path)
    args = parser.parse_args()
    generate(args.directory, args.output, args.pose_quantization)
