#!/usr/bin/env python3
"""PIPE-SPEC 3.1: convert the checked-in RGB PNG to 640x360 RGB565.

PNG filtering and nearest-neighbor resizing use only Python's standard library.
The asset is build input; generated bytes live under build/showcase/.
"""
import pathlib
import struct
import sys
import zlib

source, target = map(pathlib.Path, sys.argv[1:])
data = source.read_bytes()
offset = 8
compressed = bytearray()
while offset < len(data):
    size = struct.unpack_from('>I', data, offset)[0]
    kind = data[offset + 4:offset + 8]
    payload = data[offset + 8:offset + 8 + size]
    if kind == b'IHDR':
        width, height, depth, color, comp, filt, interlace = struct.unpack('>IIBBBBB', payload)
        if (depth, color, comp, filt, interlace) != (8, 2, 0, 0, 0):
            raise ValueError('pipe test image requires non-interlaced 8-bit RGB PNG')
    elif kind == b'IDAT':
        compressed.extend(payload)
    offset += size + 12
raw = zlib.decompress(compressed)
stride = width * 3
previous = bytearray(stride)
rows = []
for y in range(height):
    mode = raw[y * (stride + 1)]
    row = bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
    for x in range(stride):
        a = row[x - 3] if x >= 3 else 0
        b = previous[x]
        c = previous[x - 3] if x >= 3 else 0
        if mode == 0:
            predictor = 0
        elif mode == 1:
            predictor = a
        elif mode == 2:
            predictor = b
        elif mode == 3:
            predictor = (a + b) // 2
        elif mode == 4:
            estimate = a + b - c
            distances = (abs(estimate - a), abs(estimate - b), abs(estimate - c))
            predictor = (a, b, c)[distances.index(min(distances))]
        else:
            raise ValueError(f'unsupported PNG row filter {mode}')
        row[x] = (row[x] + predictor) & 255
    rows.append(row)
    previous = row
output = bytearray()
for y in range(360):
    row = rows[y * height // 360]
    for x in range(640):
        pos = (x * width // 640) * 3
        r, g, b = row[pos:pos + 3]
        output.extend(struct.pack('<H', ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)))
target.parent.mkdir(parents=True, exist_ok=True)
target.write_bytes(output)
