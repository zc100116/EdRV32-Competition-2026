class HeaderTest(unittest.TestCase):
    def test_exact_headers_boundaries_and_reference_transmit(self):
        for window in range(4):
            for length in (0, 1, 1023, 1024, 1025, 3000):
                with self.subTest(window=window, length=length):
                    data = bytes(i % 251 for i in range(length))
                    offset = 0x12345678
                    chunks = list(packets(data, window, offset))
                    self.assertEqual(len(chunks), max(1, (length + 1023) // 1024))
                    memory = {0x10000 + i: b for i, b in enumerate(data)}
                    ref = eth_ref.Reference()
                    frames = ref.transmit([0x10000, length, window | 0x100, offset], memory)
                    for index, (packet, frame) in enumerate(zip(chunks, frames)):
                        start = index * 1024
                        notify = index == len(chunks) - 1
                        header = bytes([window, int(notify), 0, 0])
                        header += (offset + start).to_bytes(4, "big")
                        self.assertEqual(packet[:8], header)
                        self.assertEqual(packet[:8], eth_ref.application(
                            window, notify, offset + start))
                        self.assertEqual(packet[8:], data[start:start + 1024])
                        self.assertLessEqual(len(packet) - 8, 1024)
                        udp_len = int.from_bytes(frame[38:40], "big")
                        self.assertEqual(packet, frame[42:34 + udp_len])

    def test_generated_datagrams_parsed_by_receive_reference(self):
        data = bytes(range(256)) * 10
        for window in range(4):
            ref = eth_ref.Reference()
            for packet in packets(data, window, 13):
                frame = eth_ref.udp(packet[8:])
                # Keep the generated bytes intact when feeding the full frame parser.
                frame = eth_ref.replace(frame, 42, packet)
                result, _ = ref.receive(frame)
                self.assertEqual(result, "write")
            base = ref.windows[window].base + 13
            self.assertEqual(bytes(ref.memory[base + i] for i in range(len(data))), data)
            self.assertEqual(ref.windows[window].count, len(data))
            self.assertEqual(ref.notify, 1 << (8 + window))

    def test_receive_ignores_reserved_header_bits(self):
        packet = bytes.fromhex("fe ff ab cd 12 34 56 78") + b"payload"
        self.assertEqual(unpack(packet), (2, True, 0x12345678, b"payload"))


class LoopbackTest(unittest.TestCase):
    def setUp(self):
        ready = patch('tools.debug_tool.core.ethernet.wait_for_link',
                      return_value=('Ethernet', 0.0))
        ready.start()
        self.addCleanup(ready.stop)
        self.temp = TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.receiver = EthernetTool(local_ip="127.0.0.1")
        self.sender = EthernetTool(local_ip="127.0.0.1")
        self.addCleanup(self.receiver.stop_receive)
        self.addCleanup(self.sender.stop_receive)

    def test_file_loopback_all_windows_and_nonzero_offset(self):
        rx = self.receiver.start_receive(0, Path(self.temp.name) / "rx")
        self.assertEqual(rx["socketBufferBytes"], self.receiver.rx_socket.getsockopt(
            socket.SOL_SOCKET, socket.SO_RCVBUF))
        expected_packets = 0
        total_bytes = 0
        for window, length in enumerate((0, 1024, 1025, 5317)):
            data = bytes(i % 251 for i in range(length))
            path = Path(self.temp.name) / f"source{window}.bin"
            path.write_bytes(data)
            offset = window * 7
            self.sender.send_file(path, "127.0.0.1", rx["localPort"], 0,
                                  window, offset, 0.001)
            wait_for(self, lambda: not self.sender.status()["tx"]["active"])
            tx = self.sender.status()["tx"]
            self.assertIsNone(tx["error"])
            self.assertEqual(tx["sent"], len(data))
            expected_packets += max(1, (length + 1023) // 1024)
            total_bytes += length
        wait_for(self, lambda: self.receiver.status()["rx"]["packets"] == expected_packets)
        rx = self.receiver.stop_receive()
        self.assertEqual(rx["bytes"], total_bytes)
        self.assertEqual(rx["notifyCount"], 4)
        self.assertTrue(rx["lastNotify"])
        for window, path in rx["files"].items():
            data = (Path(self.temp.name) / f"source{window}.bin").read_bytes()
            self.assertEqual(Path(path).read_bytes(), b"\0" * (int(window) * 7) + data)

    def test_out_of_order_notify_does_not_stop_listener(self):
        rx = self.receiver.start_receive(0, self.temp.name)
        data = bytes(range(256)) * 13
        chunks = list(packets(data, 3, 5))
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as sock:
            for packet in reversed(chunks):
                sock.sendto(packet, ("127.0.0.1", rx["localPort"]))
        wait_for(self, lambda: self.receiver.status()["rx"]["packets"] == len(chunks))
        self.assertTrue(self.receiver.status()["rx"]["active"])
        rx = self.receiver.stop_receive()
        self.assertEqual(rx["notifyCount"], 1)
        self.assertFalse(rx["lastNotify"])
        self.assertEqual(Path(rx["files"]["3"]).read_bytes(), b"\0" * 5 + data)

    def test_send_uses_listening_local_port(self):
        rx = self.receiver.start_receive(0, Path(self.temp.name) / "rx")
        sender_rx = self.sender.start_receive(0, Path(self.temp.name) / "sender")
        path = Path(self.temp.name) / "source.bin"
        path.write_bytes(b"shared UDP port")
        self.sender.send_file(path, "127.0.0.1", rx["localPort"], sender_rx["localPort"])
        wait_for(self, lambda: self.receiver.status()["rx"]["packets"] == 1)
        wait_for(self, lambda: not self.sender.status()["tx"]["active"])
        rx = self.receiver.stop_receive()
        self.assertEqual(rx["peer"], ["127.0.0.1", sender_rx["localPort"]])
        self.assertEqual(Path(rx["files"]["0"]).read_bytes(), path.read_bytes())


class BindingTest(unittest.TestCase):
    def setUp(self):
        ready = patch('tools.debug_tool.core.ethernet.wait_for_link',
                      return_value=('Ethernet', 0.0))
        ready.start()
        self.addCleanup(ready.stop)

    def test_default_local_address(self):
        self.assertEqual(EthernetTool().local_ip, '192.168.1.2')

    def test_receiver_bind_failure_is_explicit(self):
        tool = EthernetTool(local_ip='192.0.2.2')
        with (TemporaryDirectory() as directory,
              patch('tools.debug_tool.core.ethernet.socket.socket') as factory):
            sock = factory.return_value
            sock.bind.side_effect = OSError('address unavailable')
            with self.assertRaisesRegex(OSError, 'address unavailable'):
                tool.start_receive(6000, directory)
            sock.bind.assert_called_once_with(('192.0.2.2', 6000))
            sock.close.assert_called_once()
            self.assertFalse(tool.status()['rx']['active'])

    def test_sender_binds_requested_address_and_reports_failure(self):
        tool = EthernetTool(local_ip='192.0.2.2')
        tool.session = Mock()
        with patch('tools.debug_tool.core.ethernet.socket.socket') as factory:
            sock = factory.return_value
            sock.bind.side_effect = OSError('address unavailable')
            tool._send([next(packets(b'probe', 3, 0))], '192.168.1.10', 5000,
                       6000, 0, None, tool.local_ip)
            sock.bind.assert_called_once_with(('192.0.2.2', 6000))
            sock.sendto.assert_not_called()
            self.assertIn('address unavailable', tool.status()['tx']['error'])
            self.assertIn('address unavailable', tool.session.fail.call_args.args[0])

    def test_send_uses_new_address_when_listener_has_other_address(self):
        tool = EthernetTool(local_ip='127.0.0.1')
        self.addCleanup(tool.stop_receive)
        with (TemporaryDirectory() as directory,
              socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as receiver):
            tool.start_receive(0, directory)
            tool.local_ip = '127.0.0.2'
            receiver.bind(('127.0.0.1', 0))
            receiver.settimeout(2)
            path = Path(directory) / 'probe.bin'
            path.write_bytes(b'probe')
            tool.send_file(path, '127.0.0.1', receiver.getsockname()[1], 0)
            packet, source = receiver.recvfrom(1024)
            wait_for(self, lambda: not tool.status()['tx']['active'])
            self.assertEqual(packet, next(packets(b'probe', 0, 0)))
            self.assertEqual(source[0], '127.0.0.2')

    def test_sender_source_address_without_listener(self):
        tool = EthernetTool(local_ip='127.0.0.2')
        with socket.socket(socket.AF_INET, socket.SOCK_DGRAM) as receiver:
            receiver.bind(('127.0.0.1', 0))
            receiver.settimeout(2)
            packet = next(packets(b'probe', 3, 0))
            tool._send([packet], '127.0.0.1', receiver.getsockname()[1],
                       0, 0, None, tool.local_ip)
            data, source = receiver.recvfrom(1024)
            self.assertEqual(data, packet)
            self.assertEqual(source[0], '127.0.0.2')


class ReadinessTest(unittest.TestCase):
    def test_batch_waits_once_before_first_datagram(self):
        tool = EthernetTool()
        tool.tx['path'] = 'test.bin'
        tool.session = Mock()
        events = []
        sock = Mock()
        sock.sendto.side_effect = lambda *args: events.append('send')
        data = list(packets(bytes(1025), 0, 0))
        with patch('tools.debug_tool.core.ethernet.socket.socket', return_value=sock), \
                patch('tools.debug_tool.core.ethernet.wait_for_link',
                      side_effect=lambda ip: (events.append('ready') or ('Ethernet', 1.2))) as wait:
            tool._send(data, '192.168.1.10', 5000, 6000, 0, None, tool.local_ip)
        self.assertEqual(events, ['ready', 'send', 'send'])
        wait.assert_called_once_with(tool.local_ip)
        tool.session.log.assert_any_call('等待网卡 Ethernet 就绪 … 用时 1.2 s')

    def test_timeout_sends_no_datagrams(self):
        tool = EthernetTool()
        tool.session = Mock()
        with patch('tools.debug_tool.core.ethernet.socket.socket') as factory, \
                patch('tools.debug_tool.core.ethernet.wait_for_link',
                      side_effect=OSError('Ethernet timeout')):
            tool._send(list(packets(b'probe', 3, 0)), '192.168.1.10', 5000,
                       6000, 0, None, tool.local_ip)
        factory.return_value.sendto.assert_not_called()
        self.assertIn('Ethernet timeout', tool.status()['tx']['error'])

    def test_send_error_is_reported_without_retry(self):
        tool = EthernetTool()
        tool.session = Mock()
        packet = next(packets(b'probe', 3, 0))
        with patch('tools.debug_tool.core.ethernet.socket.socket') as factory, \
                patch('tools.debug_tool.core.ethernet.wait_for_link',
                      return_value=('Ethernet', 0.0)) as wait:
            factory.return_value.sendto.side_effect = OSError('send failed')
            tool._send([packet], '192.168.1.10', 5000, 6000, 0, None, tool.local_ip)
        wait.assert_called_once_with(tool.local_ip)
        factory.return_value.sendto.assert_called_once_with(packet, ('192.168.1.10', 5000))
        self.assertIn('send failed', tool.status()['tx']['error'])

    def test_win3_and_virtual_input_wait_before_single_packet(self):
        from tools.debug_tool.core.session import BoardSession
        from tools.debug_tool.core.virtual_input import send_frame
        engine = Mock()
        engine.program.status.return_value = {'error': None}
        board = BoardSession(engine)
        engine.board = board
        engine.ethernet = board.ethernet
        tool = board.ethernet
        tool.local_ip = '192.168.1.2'
        tool.rx_socket = Mock()
        tool.rx.update(active=True, localPort=6000, localIp=tool.local_ip)
        events = []
        tool.rx_socket.sendto.side_effect = lambda *args: events.append('send')
        with patch('tools.debug_tool.core.ethernet.wait_for_link',
                   side_effect=lambda ip: (events.append('ready') or ('Ethernet', .5))) as wait:
            board.establish_network()
            self.assertEqual(events, ['ready', 'send'])
            self.assertEqual(tool.rx_socket.sendto.call_args.args[0],
                             next(packets(b'\0', 3, 0)))
            from test_p5_protocol import hello
            engine.ethernet.showcase.receive(hello())
            send_frame(engine, b'input')
            self.assertEqual(events, ['ready', 'send', 'ready', 'send'])
        self.assertEqual(wait.call_count, 2)
        self.assertEqual(tool.rx_socket.sendto.call_count, 2)
