#!/usr/bin/env python3
"""font8x16.py — B2 software design 3.2: extract printable ASCII PSF1 glyphs.

Source: console-setup Lat15-Fixed16.psf.gz (console fonts are public domain).
Clock domain: offline host; output sw/lib/font8x16.h is checked in.
"""
import argparse
import gzip
from pathlib import Path
import struct


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    data = gzip.decompress(args.font.read_bytes())
    magic, mode, height = struct.unpack_from("<HBB", data)
    if magic != 0x0436 or height != 16 or not mode & 2:
        raise ValueError("font generator requires PSF1 8x16 with Unicode table")
    count = 512 if mode & 1 else 256
    glyphs = data[4:4 + count * height]
    mapping = {}
    index = 0
    for (codepoint,) in struct.iter_unpack("<H", data[4 + count * height:]):
        if codepoint == 0xffff:
            index += 1
        elif codepoint < 128:
            mapping[codepoint] = index
    lines = ["/* font8x16.h — B2 software design 3.2: printable ASCII bitmap.",
             " * Generated by tools/gen/font8x16.py from console-setup Lat15-Fixed16.psf.gz.",
             " * Console bitmap fonts are public domain (console-setup copyright).",
             " * Clock domain: CPU read-only constants. MSB is the left pixel.",
             " */", "#ifndef FONT8X16_H", "#define FONT8X16_H", "#include <stdint.h>",
             "static const uint8_t font8x16[95][16] = {"]
    for codepoint in range(32, 127):
        offset = mapping[codepoint] * 16
        values = glyphs[offset:offset + 16]
        lines.append("    {" + ", ".join(f"0x{value:02x}" for value in values[:8]) + ",")
        lines.append("        " + ", ".join(f"0x{value:02x}" for value in values[8:]) + "},")
    lines.extend(["};", "#endif"])
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
