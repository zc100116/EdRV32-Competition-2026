#!/usr/bin/env python3
"""yolo_post.py — npu-spec 2.2/2.5; B2 software design 3.4.

Generate integer exp/probability tables from compiler quantization.json.
Clock domain: offline host; runtime numerical contract: sw/lib/README.md.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/npu"))
from yolo_post_ref import make_heads


def write_tables(heads, directory):
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "yolo_tables.json").write_text(json.dumps(heads, indent=2) + "\n")
    lines = ["/* yolo_tables.c — npu-spec 2.2; B2 software design 3.4.",
             " * Generated by tools/gen/yolo_post.py; do not edit.",
             " * Clock domain: CPU read-only constants.", " */",
             '#include "yolo_post.h"', "", "const yolo_head yolo_default_heads[3] = {"]
    for head in heads:
        lines.append("    {")
        for key, value in head.items():
            if isinstance(value, list):
                lines.append(f"        .{key} = {{")
                for start in range(0, len(value), 8):
                    lines.append("            " + ", ".join(map(str, value[start:start + 8])) + ",")
                lines.append("        },")
            else:
                lines.append(f"        .{key} = {value},")
        lines.append("    },")
    lines.append("};")
    (directory / "yolo_tables.c").write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("quantization", type=Path)
    parser.add_argument("--out", type=Path, default=ROOT / "sw/lib")
    args = parser.parse_args()
    write_tables(make_heads(json.loads(args.quantization.read_text())), args.out)


if __name__ == "__main__":
    main()
