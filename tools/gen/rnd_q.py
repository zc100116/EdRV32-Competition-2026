#!/usr/bin/env python3
# File: rnd_q.py
# Spec: rnd-spec 2.2 (Q[a] reciprocal table for the ARGB8888 over operation).
# Description: Generate rtl/include/edrv32_rnd_q.vh, a Verilog-2001 function
#              holding Q[a] = floor((255*65536 + floor(a/2)) / a), Q[0] = 0.
# Clock domain: none (host tool).
"""Generate the RND Q-table function header."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'rtl' / 'include' / 'edrv32_rnd_q.vh'


def q_value(a):
    return 0 if a == 0 else (255 * 65536 + a // 2) // a


def main():
    lines = [
        '// File: edrv32_rnd_q.vh',
        '// Spec: rnd-spec 2.2 Q[a].',
        '// Description: Generated by tools/gen/rnd_q.py; do not edit. Constant',
        '//              table Q[a] = floor((255*65536 + floor(a/2)) / a), Q[0] = 0',
        '//              (oa = 0 is bypassed by the caller). Include once inside the',
        '//              module body that uses it; it synthesizes to LUT logic.',
        '// Clock domain: combinational.',
        'function [23:0] edrv32_rnd_q;',
        '    input [7:0] q_index_i;',
        '    begin',
        '        case (q_index_i)',
    ]
    for a in range(256):
        lines.append(f"            8'd{a}: edrv32_rnd_q = 24'd{q_value(a)};")
    lines += [
        "            default: edrv32_rnd_q = 24'd0;",
        '        endcase',
        '    end',
        'endfunction',
        '',
    ]
    OUT.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
