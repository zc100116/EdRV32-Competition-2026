"""Collect native NPU reports, complete warnings and compact timing details."""
from collections import Counter
import re
import shutil
import report_utils as u


ROOT = u.REPO.parent / "EdRV32-FPGA/EdRV32-NPU"
OUT = u.TASK / "artifacts"
TOP = "edrv32_fpga_npu_top"
CLOCKS = ("clk_npu", "clk_mem")


def timing_section(text):
    return text.split("\nSlow Corner", 1)[0]


def detailed(records, count=20):
    return "\n\n".join(p["block"] for clock in CLOCKS for corner in ("slow", "fast")
                        for p in [x for x in records if x["group"] == clock
                                  and x["corner"] == corner][:count])


def collect():
    native = [
        ("compile", f"{TOP}.cmr"), ("compile", "include_relation.txt"),
        ("synthesize", f"{TOP}.snr"), ("synthesize", f"{TOP}_controlsets.txt"),
        ("synthesize", "apm_drm_lutram_utilization.log"),
        ("synthesize", "add_sub_carrychain.log"),
        ("device_map", f"{TOP}.dmr"), ("device_map", f"{TOP}_dmr.prt"),
        ("place_route", f"{TOP}.prr"), ("place_route", f"{TOP}_prr.prt"),
        ("place_route", "clock_utilization.txt"),
        ("report_timing", f"{TOP}.rtr"),
        ("constraint_check", "constraint_check.ccr"),
    ]
    for stage, name in native:
        dst = OUT / "native_reports" / stage / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / stage / name, dst)
    summaries, warnings, excerpts = [], [], []
    for stage in u.STAGES:
        raw = u.read(ROOT / stage / "run.log")
        ws = [l for l in raw.splitlines() if l.startswith("W:")]
        es = [l for l in raw.splitlines() if l.startswith("E:")]
        counts = Counter(u.warning_category(l) for l in ws)
        summaries += [f"STAGE {stage}: Errors={len(es)} Warnings={len(ws)}"]
        summaries += [f"{k}\t{v}" for k, v in counts.most_common()]
        summaries += [l for l in raw.splitlines()
                      if l.startswith(("Action ", "Current time:"))] + [""]
        warnings += [f"STAGE {stage}: {ROOT / stage / 'run.log'}"] + ws + es + [""]
        excerpts += [f"STAGE {stage}"] + [l for l in raw.splitlines() if
                     l.startswith(("#", "Generated by", "Start ", "Current time:", "Action ",
                                   "Process ", "Phase ", "Placement ", "Routing ", "Total ",
                                   "Program Error", "Finished ", "Design '"))
                     or re.search(r"takes .*sec", l)
                     or (l.startswith("Executing :") and "Time elapsed:" in l)] + [""]
    u.write(OUT / "flow_summary.txt", "Final stage logs from the K21 rerun (timestamps below).\n"
            "W/E counts are log lines, not distinct defects.\n\n" + "\n".join(summaries))
    u.write(OUT / "logs/warnings_detail.txt", "\n".join(warnings))
    u.write(OUT / "logs/execution_excerpt.txt", "\n".join(excerpts))
    project = [l for l in u.read(ROOT / "pds.log").splitlines() if
               re.match(r"^(Executing : (?:source |compile |synthesize |dev_map|pnr|report_timing)"
                        r"|[EC]:|Current time:|Action |Process )", l)]
    u.write(OUT / "logs/project_actions_excerpt.txt",
            "Historical actions include the previous B24 failure and earlier imports.\n"
            "Use flow_summary.txt for final per-stage status.\n" + "\n".join(project))
    prr = u.read(ROOT / "place_route" / f"{TOP}.prr")
    dmr = u.read(ROOT / "device_map" / f"{TOP}.dmr")
    snr = u.read(ROOT / "synthesize" / f"{TOP}.snr")
    hierarchy, entries = u.hierarchy(prr)
    own_lut = entries[0]["values"][0] - entries[1]["values"][0]
    own_ff = entries[0]["values"][1] - entries[1]["values"][1] - 4
    u.write(OUT / "resource_hier.txt", "Source: final PnR PRR\n" + hierarchy +
            f"\nTop local excluding u_npu and two reset synchronizers: {own_lut} LUT, {own_ff} FF.\n"
            "This aggregate includes stimulus/observation logic; per-bank optimized FF counts "
            "are not separately reported. Do not sum parent and child rows.")
    synth_usage = snr[snr.index("Cell Usage:"):snr.index("Overview of Control Sets:")]
    u.write(OUT / "resource_summary.txt",
            "Final logical total, columns LUT/FF/distributed RAM/APM/DRM36K-equivalent:\n"
            + str(entries[0]["values"]) + "\n\n" +
            u.section(prr, "Device Utilization Summary :") +
            "\n\nSYNTHESIS STAGE, not final logical counts:\n" + synth_usage +
            "\nDRM18K=0; DRM36K=157 (SNR primitive counts; PRR total also 157).\n"
            "GPLL=0, PPLL=0, USCM=2, IO=6.\n"
            "Final logical LUT=27188/159800 (17.0138%); FF=36481/319600 (11.4146%);\n"
            "distributed RAM=412/39500 (1.0430%); APM=290/740 (39.1892%);\n"
            "DRM36K=157/415 (37.8313%); IO=6/400 (1.5%).\n"
            "Physical CLMA/CLMS LUT rows have a different packing basis from logical LUT totals.")
    u.write(OUT / "high_fanout.txt", "Source: DEVICE MAP, before PnR\n\n" +
            "\n\n".join(u.section(dmr, t) for t in
                         ("Other High Fanout Signal:", "Clock Signal:", "Reset Signal:",
                          "CE Signal:")) + "\n\nFinal PnR:\n" +
            u.section(prr, "Global Clock Info:"))
    fdc = u.read(u.REPO / "fpga/constraints/edrv32_fpga_npu_top.fdc")
    impl = u.read(ROOT / "impl.tcl")
    pnrlog = u.read(ROOT / "place_route/run.log")
    u.write(OUT / "clock_constraints.txt",
            "Project constraint reference:\n" + "\n".join(l for l in impl.splitlines()
             if l.startswith("add_constraint")) + "\n\nRepository FDC:\n" + fdc +
            "\nPnR applied pin constraints:\n" + "\n".join(l for l in pnrlog.splitlines()
             if l.startswith("Executing : def_port")) + "\n\n" +
            u.section(prr, "Global Clock Info:") +
            "\nNo PAP_CLOCK_DEDICATED_ROUTE relaxation in the FDC or implementation command file.")
    original = u.read(ROOT / "report_timing" / f"{TOP}.rtr")
    u.write(OUT / "timing_summary.txt",
            "Fmax = 1000 / (period - slow WNS) MHz.\n"
            "clk_npu: 1000/(6.667-0.214)=154.9667 MHz.\n"
            "clk_mem: 1000/(8.000-4.448)=281.5315 MHz.\n\n" + timing_section(original))
    expanded = u.paths(u.read(u.BUILD / f"timing_200/report_timing/{TOP}.rtr"), "global200")
    setup = [p for p in expanded if p["type"].startswith("max")
             and p["class"] == "sequential timing path"]
    hold = [p for p in expanded if p["type"].startswith("min")
            and p["class"] == "sequential timing path"]
    u.write(OUT / "setup_top200.txt", u.index_text(setup))
    u.write(OUT / "setup_top20_detail.txt", detailed(setup))
    u.write(OUT / "hold_top200.txt", u.index_text(hold))
    u.write(OUT / "hold_top20.txt", detailed(hold))
    asyncs = [p for p in expanded if p["class"] == "async timing path"]
    u.write(OUT / "recovery_removal_top20.txt", "\n\n".join(
        p["block"] for clock in CLOCKS for corner in ("slow", "fast") for direction in ("max", "min")
        for p in [x for x in asyncs if x["group"] == clock and x["corner"] == corner
                  and x["type"].startswith(direction)][:20]))
    u.write(OUT / "unconstrained_io_paths.txt",
            "Unconstrained paths have no slack/pass verdict.\n\n" + "\n\n".join(
                p["block"] for p in expanded if p["class"] == "combinational timing path"))
    near = u.paths(u.read(u.BUILD / f"timing_near/report_timing/{TOP}.rtr"), "positive_lt1ns")
    u.write(OUT / "setup_near_positive_top200.txt", u.index_text(near))
    u.write(OUT / "setup_near_positive_top20_detail.txt", detailed(near))
    notes = ["Expanded timing reports were generated into separate scratch projects.",
             "Original routed DB and FPGA project were not modified; PnR was not rerun."]
    for name in ("timing_200", "timing_near"):
        notes += [name] + [l for l in u.read(u.BUILD / name / "console.log").splitlines()
                         if l.startswith(("Executing : report_timing", "W:", "E:", "C:",
                                          "Action ", "Process "))]
    u.write(OUT / "logs/timing_export_excerpt.txt", "\n".join(notes))
    print("Setup:", Counter((p["group"], p["corner"]) for p in setup))
    print("Hold:", Counter((p["group"], p["corner"]) for p in hold))
    print("Final resources:", entries[0]["values"])


if __name__ == "__main__":
    collect()
