"""Collect successful NPU front-end stages and the failed clock placement."""
from collections import Counter
import re
import shutil
import xml.etree.ElementTree as ET
import collect_reports as c


ROOT = c.REPO.parent / "EdRV32-FPGA/EdRV32-NPU"
OUT = c.TASK / "artifacts/npu"
TOP = "edrv32_fpga_npu_top"


def collect():
    reports = [
        ("compile", f"{TOP}.cmr"), ("compile", "include_relation.txt"),
        ("synthesize", f"{TOP}.snr"),
        ("synthesize", f"{TOP}_controlsets.txt"),
        ("synthesize", "apm_drm_lutram_utilization.log"),
        ("synthesize", "add_sub_carrychain.log"),
        ("device_map", f"{TOP}.dmr"), ("device_map", f"{TOP}_dmr.prt"),
        ("place_route", f"{TOP}.prr"),
        ("place_route", "clock_utilization.txt"),
        ("constraint_check", "constraint_check.ccr"),
    ]
    for stage, name in reports:
        dst = OUT / "native_reports" / stage / name
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT / stage / name, dst)
    summaries, warnings, excerpts = [], [], []
    for stage in c.STAGES[:-1]:
        raw = c.read(ROOT / stage / "run.log")
        ws = [line for line in raw.splitlines() if line.startswith("W:")]
        es = [line for line in raw.splitlines() if line.startswith("E:")]
        counts = Counter(c.warning_category(line) for line in ws)
        summaries += [f"STAGE {stage}: Errors={len(es)} Warnings={len(ws)}"]
        summaries += [f"{key}\t{value}" for key, value in counts.most_common()]
        summaries += [line for line in raw.splitlines()
                      if line.startswith(("Action ", "Current time:"))] + [""]
        warnings += [f"STAGE {stage}: {ROOT / stage / 'run.log'}"] + ws + es + [""]
        excerpts += [f"STAGE {stage}"] + [line for line in raw.splitlines() if
                     line.startswith(("#", "Generated by", "Start ", "Current time:",
                                      "Action ", "Process ", "Program Error", "Phase ",
                                      "Placement ", "Routing ", "Total "))
                     or re.search(r"takes .*sec", line)
                     or (line.startswith("Executing :") and "Time elapsed:" in line)] + [""]
    c.write(OUT / "flow_summary.txt", "\n".join(summaries) +
            "\nreport_timing: 未运行；PnR 在 Phase 1.2 Clock placement 失败。")
    c.write(OUT / "logs/warnings_detail.txt", "\n".join(warnings))
    c.write(OUT / "logs/execution_excerpt.txt", "\n".join(excerpts))
    failed = c.read(ROOT / "place_route/run.log")
    c.write(OUT / "logs/pnr_failure_excerpt.txt",
            f"Source: {ROOT / 'place_route/run.log'}\n\n" +
            failed[failed.index("Phase 1.2 Clock placement started."):])
    actions = [line for line in c.read(ROOT / "pds.log").splitlines() if
               re.match(r"^(Executing : (?:source |compile |synthesize |dev_map|pnr|report_timing)"
                        r"|[EC]:|Current time:|Action |Process )", line)]
    c.write(OUT / "logs/project_actions_excerpt.txt",
            "Historical project actions include earlier failed imports; "
            "use flow_summary.txt for final-stage status.\n" + "\n".join(actions))
    snr = c.read(ROOT / "synthesize" / f"{TOP}.snr")
    dmr = c.read(ROOT / "device_map" / f"{TOP}.dmr")
    table, entries = c.hierarchy(snr)
    c.write(OUT / "resource_hier.txt", "Source: SYNTHESIS SNR, not final PnR\n" + table +
            "\nTop local (total - u_npu - two reset synchronizers): "
            "75 LUT, 435 FF; aggregate includes serial stimulus and observation logic.\n"
            "Individual stim/obs bank resource counts are not separately reported.")
    usage = snr[snr.index("Cell Usage:"):snr.index("Overview of Control Sets:")]
    c.write(OUT / "resource_summary.txt", "SYNTHESIS (not PnR):\n" + usage +
            "\nDRM18K=0; DRM36K=157. GPLL=0; PPLL=0.\n"
            "DEVICE MAP (last successful physical mapping stage):\n" +
            c.section(dmr, "Device Utilization Summary:") +
            "\nMapped logical LUT=27372, FF=36481, distributed RAM=412, "
            "APM=290, DRM36K=157, IO=6, USCM=2.\n"
            "Final post-PnR resource counts: 未取得 (Place-0084).")
    head = snr[snr.index("Timing analysis mode"):snr.index("Startpoint")]
    c.write(OUT / "timing_synthesis_estimate.txt",
            "SYNTHESIS ESTIMATE ONLY; single corner, no routed timing.\n" + head)
    missing = ("未取得：2026-10-28 完整 NPU 的 PnR 在 Phase 1.2 Clock placement 因 "
               "Place-0084 失败；没有 routed pnr.adf，也未运行路后 report_timing。\n"
               "不得用前一轮 NPU-DP 或本轮综合预估代替完整 NPU 的路后数据。\n")
    for name in ("timing_summary.txt", "setup_top200.txt", "setup_top20_detail.txt",
                 "hold_top20.txt", "setup_group_detail.txt"):
        c.write(OUT / name, missing)
    c.write(OUT / "high_fanout.txt", "Source: DEVICE MAP DMR (pre-PnR)\n" +
            "\n\n".join(c.section(dmr, title) for title in
                         ("Other High Fanout Signal:", "Clock Signal:",
                          "Reset Signal:", "CE Signal:")))
    # Retain all available synthesis paths with an explicit stage label.
    records = c.paths(snr, "synthesis_estimate")
    c.write(OUT / "setup_synthesis_paths.txt", c.index_text([
        p for p in records if p["type"].startswith("max")
        and p["class"] == "sequential timing path"]))
    c.write(OUT / "setup_synthesis_detail.txt", "SYNTHESIS ESTIMATE ONLY\n\n" +
            "\n\n".join(p["block"] for p in records if p["type"].startswith("max")
                         and p["class"] == "sequential timing path"))
    ip_ports(entries)
    print("NPU collected", entries[0]["values"], flush=True)


def ip_ports(entries):
    iproot = c.REPO.parent / "EdRV32-FPGA/EdRV32-NPU-DP/ipcore"
    text = ["# 完整 NPU 的 9 个 IP 核对", "",
            "来源：全部沿用 `G:/codex_project/EdRV32-FPGA/EdRV32-NPU-DP/ipcore/`；"
            "完整 NPU CMR 列出这 9 个 .idf，Compile/Synthesize 均完成。",
            "本轮没有修改 RTL 包装或重新生成 IP。以下配置与端口摘自实际生成的 .idf/.v。", ""]
    for idf in sorted(iproot.glob("*/*.idf")):
        name = idf.stem
        xml = ET.parse(idf).getroot()
        params = {p.findtext("name"): p.findtext("value")
                  for p in xml.findall("param_list/param")}
        source = c.read(idf.with_suffix(".v"))
        module_ports = re.search(r"module\s+" + name + r"\s*\((.*?)\);",
                                 source, re.S)[1]
        module_ports = re.sub(r"//[^\n]*", "", module_ports)
        ports = re.findall(r"\b\w+\b", module_ports)
        wrapper = c.read(c.REPO / "rtl/tech" / f"edrv32_{name[3:]}.v")
        inst = re.search(r"\b" + name + r"\s+u_ip\s*\((.*?)\);", wrapper, re.S)[1]
        connected = re.findall(r"\.(\w+)\s*\(", inst)
        same = set(ports) == set(connected)
        used = [e for e in entries if e["name"] in (
            "U_ipm2l_sdpram_" + name, "u_ipm2l_mult_" + name)]
        drm = sum(e["values"][4] for e in used)
        apm = sum(e["values"][3] for e in used)
        text += [f"## {name}", "", f"- 模块名：`{name}`；封装：{xml.findtext('header/package')}。",
                 f"- 端口：`{', '.join(ports)}`；包装端口集合"
                 + ("一致。" if same else "不一致：" + str(connected)),
                 f"- SNR 层次中 {len(used)} 个实例，合计 DRM36K={drm}，APM={apm}。"]
        keys = ("WR_ADDR_WIDTH", "WR_DATA_WIDTH", "RD_ADDR_WIDTH", "RD_DATA_WIDTH",
                "OUTPUT_REG", "RD_CLK_EN", "WR_CLK_EN", "RESET_TYPE", "CAS_MODE",
                "ASIZE", "BSIZE", "A_SIGNED", "B_SIGNED", "XYREG", "MREG", "PREG")
        text += ["- 配置：" + "; ".join(f"{k}={params[k]}" for k in keys if k in params), ""]
        if "ip_mul_" in name:
            actual = dict(re.findall(r"localparam\s+(\w+)\s*=\s*([^;]+);", source))
            text += ["- 生成 .v 中实际流水：" + "; ".join(
                f"{k}={actual[k].strip()}" for k in
                ("XYREG", "MREG", "PREG", "INREG", "OUTREG")) + "。", ""]
    text += ["7 个 RAM 的 wr_rst、rd_rst 在包装内接 1'b0，按前轮确认保留；"
             "两个量化乘法器同样 rst=1'b0、ce=1'b1。",
             "DRM18K=0；整机 DRM36K=157、APM=290 以 SNR 总计为准，"
             "还包含直接例化原语及推断存储，不等于上面 9 类 IP 的简单求和。"]
    c.write(OUT / "ip_ports.md", "\n".join(text))


if __name__ == "__main__":
    collect()
